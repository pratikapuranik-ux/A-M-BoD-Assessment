"""Writes js/data/base.js: the framework with no company loaded (convert.base_view()). Usage: python tools/build_base.py"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "server"))
import convert  # noqa: E402

out = os.path.join(ROOT, "js", "data", "base.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build_base.py from skill/assets/framework.json: the framework with no company loaded. */\n")
    f.write("let D=" + json.dumps(convert.base_view(), ensure_ascii=False, separators=(",", ":")) + ";\n")
print("Wrote js/data/base.js")
